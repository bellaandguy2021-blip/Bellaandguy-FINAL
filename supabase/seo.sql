-- Run this once in the Supabase Dashboard → SQL Editor.
-- SEO management tables for the admin panel's SEO tab.
--
--  • page_seo   — per-page metadata overrides (title, description, OG, robots…).
--                 Reads are public because the live site's metadata generator
--                 merges these rows into every page's <head>.
--  • redirects  — admin-managed 301/302 redirects, applied by proxy.ts.
--
-- Also adds an editable alt_text column to gallery_images (falls back to label).

create table if not exists public.page_seo (
  path            text primary key,          -- e.g. '/', '/about', '/services/facial/hydra-shine-facial'
  title           text,
  description     text,
  focus_keyword   text,
  canonical_url   text,                      -- absolute or site-relative; empty = auto (site URL + path)
  robots_index    boolean not null default true,
  robots_follow   boolean not null default true,
  og_title        text,
  og_description  text,
  og_image        text,
  twitter_card    text not null default 'summary_large_image',
  twitter_title   text,
  twitter_description text,
  updated_at      timestamptz not null default now()
);

alter table public.page_seo enable row level security;

create policy "Anyone can view page seo"
  on public.page_seo for select
  to anon, authenticated
  using (true);

create policy "Staff can insert page seo"
  on public.page_seo for insert
  to authenticated
  with check (true);

create policy "Staff can update page seo"
  on public.page_seo for update
  to authenticated
  using (true);

create policy "Staff can delete page seo"
  on public.page_seo for delete
  to authenticated
  using (true);

create table if not exists public.redirects (
  id          bigint generated by default as identity primary key,
  from_path   text not null unique,          -- e.g. '/old-page'
  to_path     text not null,                 -- e.g. '/about' or absolute URL
  status_code int  not null default 301,     -- 301 permanent | 302 temporary
  enabled     boolean not null default true,
  created_at  timestamptz not null default now()
);

alter table public.redirects enable row level security;

create policy "Anyone can view redirects"
  on public.redirects for select
  to anon, authenticated
  using (true);

create policy "Staff can insert redirects"
  on public.redirects for insert
  to authenticated
  with check (true);

create policy "Staff can update redirects"
  on public.redirects for update
  to authenticated
  using (true);

create policy "Staff can delete redirects"
  on public.redirects for delete
  to authenticated
  using (true);

-- Editable image alt text (Image SEO). The site falls back to `label` when empty.
alter table public.gallery_images add column if not exists alt_text text;
